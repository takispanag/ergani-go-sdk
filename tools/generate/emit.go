package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// The emission of the Go code.
//
// One table drives the wire structs, the public models, the translation
// between them and the submission methods, so the four cannot drift apart.

// The header of every file the generator writes.
const generatedHeader = "// Code generated by tools/generate. DO NOT EDIT."

// code collects the lines of a file of Go code.
type code struct {
	lines []string
}

// line adds a line of code as it is.
func (c *code) line(text string) {
	c.lines = append(c.lines, text)
}

// printf adds a line of code, with the values of a format.
func (c *code) printf(format string, args ...any) {
	c.lines = append(c.lines, fmt.Sprintf(format, args...))
}

// text returns the code of the file.
func (c *code) text() string {
	return strings.Join(c.lines, "\n") + "\n"
}

// write writes the code of the file.
//
// The code is formatted with the standard library, so that the file the
// generator writes is the file the gofmt would write.
func (c *code) write(path string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("ergani: the directory of %s could not be made: %w", path, err)
	}

	source, err := format.Source([]byte(c.text()))
	if err != nil {
		return fmt.Errorf("ergani: the code of %s could not be formatted: %w", path, err)
	}

	if err := os.WriteFile(path, source, 0o644); err != nil {
		return fmt.Errorf("ergani: %s could not be written: %w", path, err)
	}

	return nil
}

// emitWire writes the wire structs.
func (g *generator) emitWire() error {
	out := &code{}
	out.line(generatedHeader)
	out.line("")
	out.line("package wire")
	out.line("")

	for _, entry := range g.groups {
		spec := entry.spec

		out.printf("// %s is the flat set of the fields of a %s declaration.", spec.wire, strings.ToLower(spec.kind))
		out.printf("type %s struct {", spec.wire)

		for _, name := range g.allFields(entry) {
			info := g.variantInfo(entry.variants[0], name)
			kind, public := g.fieldKind(name, entry.variants[0].xsd, info, false)

			if strings.HasPrefix(kind, "nested:") {
				sub := wireNestedName(spec.kind, name)
				out.printf("\t%s %sPayload `json:%q`", public, sub, name)

				continue
			}

			out.printf("\t%s %s `json:%q`", public, wireTypeLocal(kind), name)
		}

		out.line("}")
		out.line("")
	}

	// The types of the nested objects. The API names the inner object after
	// the declaration type, so the wire keeps a map keyed by that name.
	seen := map[string]bool{}
	for _, entry := range g.groups {
		kind := entry.spec.kind

		for _, name := range g.allFields(entry) {
			info := g.nestedEntry(entry, name)
			if info == nil {
				continue
			}

			sub := wireNestedName(kind, name)
			if seen[sub] {
				continue
			}
			seen[sub] = true

			innerName := sub
			if isList(info) {
				innerName = sub + "Entry"
			}

			out.printf("// %sPayload is a nested object of a %s declaration.", sub, strings.ToLower(kind))
			if isList(info) {
				out.printf("type %sPayload map[string][]%s", sub, innerName)
			} else {
				out.printf("type %sPayload map[string]%s", sub, innerName)
			}
			out.line("")
			out.printf("// %s is the inner object of a nested object of a %s declaration.", innerName, strings.ToLower(kind))
			out.printf("type %s struct {", innerName)

			required := g.innerPresence(entry, name)
			for _, inner := range g.nestedUnionFields(entry, name) {
				innerKind, innerName := g.fieldKind(inner.name, entry.variants[0].xsd, inner.info, !required[inner.name])
				omit := ""
				if strings.HasPrefix(innerKind, optionalPrefix) {
					omit = ",omitempty"
				}
				out.printf("\t%s %s `json:\"%s%s\"`", innerName, wireTypeLocal(innerKind), inner.name, omit)
			}

			out.line("}")
			out.line("")
		}
	}

	return out.write(filepath.Join(g.root, "internal", "wire", "declarations.go"))
}

// emitPublic writes the public models.
func (g *generator) emitPublic() error {
	out := &code{}
	out.line(generatedHeader)
	out.line("")
	out.line("package ergani")
	out.line("")
	out.line(`import "time"`)
	out.line("")

	for _, entry := range g.groups {
		spec := entry.spec

		out.printf("// %s is the declaration of the %s of an employer.", spec.decl, strings.ToLower(spec.kind))
		out.printf("type %s struct {", spec.decl)

		for _, name := range g.allFields(entry) {
			info := g.variantInfo(entry.variants[0], name)
			kind, public := g.fieldKind(name, entry.variants[0].xsd, info, false)

			if doc := g.docs[name]; doc != "" {
				out.printf("\t// %s — %s", public, doc)
			}

			if strings.HasPrefix(kind, "nested:") {
				sub := nestedName(spec.kind, name)
				pointer := "*"
				if kind == "nested:List" {
					pointer = "[]"
				}
				out.printf("\t%s %s%s", public, pointer, sub)

				continue
			}

			out.printf("\t%s %s", public, publicType(kind))
		}

		out.line("}")
		out.line("")
	}

	// The types of the nested objects.
	seen := map[string]bool{}
	for _, entry := range g.groups {
		kind := entry.spec.kind

		for _, name := range g.allFields(entry) {
			info := g.nestedEntry(entry, name)
			if info == nil {
				continue
			}

			sub := nestedName(kind, name)
			if seen[sub] {
				continue
			}
			seen[sub] = true

			out.printf("// %s is a part of a %s declaration.", sub, strings.ToLower(kind))
			out.printf("type %s struct {", sub)

			required := g.innerPresence(entry, name)
			for _, inner := range g.nestedUnionFields(entry, name) {
				innerKind, innerName := g.fieldKind(inner.name, entry.variants[0].xsd, inner.info, !required[inner.name])

				if doc := g.docs[inner.name]; doc != "" {
					out.printf("\t// %s — %s", innerName, doc)
				}
				out.printf("\t%s %s", innerName, publicType(innerKind))
			}

			out.line("}")
			out.line("")
		}
	}

	return out.write(filepath.Join(g.root, "declarations.go"))
}

// emitTranslation writes the translation between the public models and the
// wire format.
func (g *generator) emitTranslation() error {
	// The translation is written first, because the kinds of the optional
	// values it uses are what the imports of the file depend on.
	mapping := &code{}
	g.emitMapping(mapping)

	helpers := &code{}
	g.emitOptionalHelpers(helpers)

	body := &code{}

	body.line("import (")
	body.line("\t\"context\"")
	body.line("\t\"encoding/base64\"")
	body.line("\t\"encoding/json\"")
	body.line("\t\"fmt\"")
	if g.usedOptional["date"] || g.usedOptional["datetime"] || g.usedOptional["time"] {
		body.line("\t\"time\"")
	}
	body.line("")
	body.line("\t\"github.com/takispanag/ergani-go-sdk/internal/wire\"")
	body.line(")")

	body.line("")
	body.line("// declarationFields turns a payload into the map of its fields, so that the")
	body.line("// fields a declaration type does not carry can be left out.")
	body.line("func declarationFields(payload any) (map[string]any, error) {")
	body.line("\traw, err := json.Marshal(payload)")
	body.line("\tif err != nil {")
	body.line("\t\treturn nil, fmt.Errorf(\"ergani: failed to marshal the declaration: %w\", err)")
	body.line("\t}")
	body.line("")
	body.line("\tfields := map[string]any{}")
	body.line("\tif err := json.Unmarshal(raw, &fields); err != nil {")
	body.line("\t\treturn nil, fmt.Errorf(\"ergani: failed to decode the declaration: %w\", err)")
	body.line("\t}")
	body.line("")
	body.line("\treturn fields, nil")
	body.line("}")
	body.line("")

	body.line("// dropFields removes the named fields from a payload.")
	body.line("func dropFields(fields map[string]any, names []string) {")
	body.line("\tfor _, name := range names {")
	body.line("\t\tdelete(fields, name)")
	body.line("\t}")
	body.line("}")
	body.line("")

	body.line("// boolPtr turns the API encoding of an optional boolean into a pointer.")
	body.line("//")
	body.line("// The API leaves a boolean empty when it is not answered, so the three")
	body.line("// states are kept apart.")
	body.line("func boolPtr(value wire.Bool) *bool {")
	body.line("\tif value == \"\" {")
	body.line("\t\treturn nil")
	body.line("\t}")
	body.line("")
	body.line("\tanswer := value == wire.True")
	body.line("")
	body.line("\treturn &answer")
	body.line("}")
	body.line("")

	body.line("// base64Bytes decodes a document of the API.")
	body.line("//")
	body.line("// A document that cannot be decoded yields no bytes rather than an error:")
	body.line("// the API has published a reference payload with a document that is not")
	body.line("// valid Base64, and a client must not fail on a document it only passes")
	body.line("// through.")
	body.line("func base64Bytes(value wire.Base64) []byte {")
	body.line("\tdecoded, err := base64.StdEncoding.DecodeString(string(value))")
	body.line("\tif err != nil {")
	body.line("\t\treturn nil")
	body.line("\t}")
	body.line("")
	body.line("\treturn decoded")
	body.line("}")
	body.line("")

	for _, line := range mapping.lines {
		body.line(line)
	}
	for _, line := range helpers.lines {
		body.line(line)
	}

	out := &code{}
	out.line(generatedHeader)
	out.line("")
	out.line("package ergani")
	out.line("")
	for _, line := range body.lines {
		out.line(line)
	}

	return out.write(filepath.Join(g.root, "declarations_wire.go"))
}

// emitMapping writes the translation of every family of declarations.
func (g *generator) emitMapping(out *code) {
	for _, entry := range g.groups {
		spec := entry.spec
		kind := spec.kind
		lower := lowerName(kind)
		payloadOf := lower + "PayloadOf"
		declarationOf := lower + "DeclarationOf"

		out.printf("// %s turns a %s into the payload of the API.", payloadOf, spec.decl)
		out.printf("func %s(d %s) wire.%s {", payloadOf, spec.decl, spec.wire)
		out.printf("\tp := wire.%s{}", spec.wire)

		for _, name := range g.allFields(entry) {
			info := g.variantInfo(entry.variants[0], name)
			fieldKind, public := g.fieldKind(name, entry.variants[0].xsd, info, false)

			if strings.HasPrefix(fieldKind, "nested:") {
				// The inner object of a nested object is named after the
				// declaration type, so it is built where the variant is
				// known.
				continue
			}

			out.printf("\tp.%s = %s", public, strings.ReplaceAll(g.convert(fieldKind), "{v}", "d."+public))
		}

		out.line("\treturn p")
		out.line("}")
		out.line("")

		out.printf("// %s turns a payload of the API into a %s.", declarationOf, spec.decl)
		out.printf("func %s(p wire.%s) %s {", declarationOf, spec.wire, spec.decl)
		out.printf("\tvar d %s", spec.decl)

		for _, name := range g.allFields(entry) {
			info := g.variantInfo(entry.variants[0], name)
			fieldKind, public := g.fieldKind(name, entry.variants[0].xsd, info, false)

			if strings.HasPrefix(fieldKind, "nested:") {
				sub := nestedName(kind, name)
				out.printf("\td.%s = %sOf(p.%s)", public, lower+sub, public)

				continue
			}

			out.printf("\td.%s = %s", public, strings.ReplaceAll(g.convertBack(fieldKind), "{v}", "p."+public))
		}

		out.line("\treturn d")
		out.line("}")
		out.line("")

		// The helpers of the nested objects. The API names the inner object
		// after the declaration type, so the public type stays the same for
		// every variant and the wire layer does the renaming.
		for _, name := range g.allFields(entry) {
			info := g.nestedEntry(entry, name)
			if info == nil {
				continue
			}

			sub := nestedName(kind, name)
			wireSub := wireNestedName(kind, name)
			helper := lower + sub

			innerName := wireSub
			if isList(info) {
				innerName = wireSub + "Entry"
			}

			perVariant := g.nestedVariants(entry, name)
			required := g.innerPresence(entry, name)

			out.printf("// %s builds a nested object of a %s declaration.", helper, strings.ToLower(kind))
			if isList(info) {
				out.printf("func %s(variant %s, value []%s) wire.%sPayload {", helper, spec.variant, sub, wireSub)
				out.line("\tif len(value) == 0 {")
				out.line("\t\treturn nil")
				out.line("\t}")
			} else {
				out.printf("func %s(variant %s, value *%s) wire.%sPayload {", helper, spec.variant, sub, wireSub)
				out.line("\tif value == nil {")
				out.line("\t\treturn nil")
				out.line("\t}")
			}
			out.line("")
			out.line("\tswitch variant {")

			for _, item := range entry.variants {
				variantInfo := g.variantInfo(item, name)
				if variantInfo == nil || !variantInfo.nested {
					continue
				}

				out.printf("\tcase %s:", semanticName(item.code))

				if isList(info) {
					out.printf("\t\tentries := make([]wire.%s, 0, len(value))", innerName)
					out.line("\t\tfor _, item := range value {")
					out.printf("\t\t\tentries = append(entries, wire.%s{", innerName)

					for _, inner := range perVariant[item.code] {
						innerKind, innerName := g.fieldKind(inner.name, entry.variants[0].xsd, inner.info, !required[inner.name])
						out.printf("\t\t\t\t%s: %s,", innerName, strings.ReplaceAll(g.convert(innerKind), "{v}", "item."+innerName))
					}

					out.line("\t\t\t})")
					out.line("\t\t}")
					out.printf("\t\treturn wire.%sPayload{", wireSub)
					out.printf("\t\t\t%q: entries,", variantInfo.innerKey)
					out.line("\t\t}")
				} else {
					out.printf("\t\treturn wire.%sPayload{", wireSub)
					out.printf("\t\t\t%q: wire.%s{", variantInfo.innerKey, innerName)

					for _, inner := range perVariant[item.code] {
						innerKind, innerName := g.fieldKind(inner.name, entry.variants[0].xsd, inner.info, !required[inner.name])
						out.printf("\t\t\t\t%s: %s,", innerName, strings.ReplaceAll(g.convert(innerKind), "{v}", "value."+innerName))
					}

					out.line("\t\t\t},")
					out.line("\t\t}")
				}
			}

			out.line("\tdefault:")
			out.line("\t\treturn nil")
			out.line("\t}")
			out.line("}")
			out.line("")

			out.printf("// %sOf reads a nested object of a %s declaration.", helper, strings.ToLower(kind))
			if isList(info) {
				out.printf("func %sOf(payload wire.%sPayload) []%s {", helper, wireSub, sub)
				out.line("\tfor _, entries := range payload {")
				out.printf("\t\tvalue := make([]%s, 0, len(entries))", sub)
				out.line("\t\tfor _, entry := range entries {")
				out.printf("\t\t\titem := %s{}", sub)

				for _, inner := range g.nestedUnionFields(entry, name) {
					innerKind, innerName := g.fieldKind(inner.name, entry.variants[0].xsd, inner.info, !required[inner.name])
					out.printf("\t\t\titem.%s = %s", innerName, strings.ReplaceAll(g.convertBack(innerKind), "{v}", "entry."+innerName))
				}

				out.line("\t\t\tvalue = append(value, item)")
				out.line("\t\t}")
				out.line("\t\treturn value")
				out.line("\t}")
				out.line("\treturn nil")
				out.line("}")
				out.line("")
			} else {
				out.printf("func %sOf(payload wire.%sPayload) *%s {", helper, wireSub, sub)
				out.line("\tfor _, entry := range payload {")
				out.printf("\t\tvalue := &%s{}", sub)

				for _, inner := range g.nestedUnionFields(entry, name) {
					innerKind, innerName := g.fieldKind(inner.name, entry.variants[0].xsd, inner.info, !required[inner.name])
					out.printf("\t\tvalue.%s = %s", innerName, strings.ReplaceAll(g.convertBack(innerKind), "{v}", "entry."+innerName))
				}

				out.line("\t\treturn value")
				out.line("\t}")
				out.line("\treturn nil")
				out.line("}")
				out.line("")
			}
		}

		out.printf("// %s is a type of the %s declaration.", spec.variant, strings.ToLower(kind))
		out.printf("type %s string", spec.variant)
		out.line("")
		out.line("// The declarations of the family.")
		out.line("const (")

		for _, item := range entry.variants {
			name := semanticName(item.code)
			out.printf("\t// %s is the %s declaration.", name, item.family)
			out.printf("\t%s %s = %q", name, spec.variant, item.code)
		}

		out.line(")")
		out.line("")

		out.printf("// %sEnvelopeKeys returns the root and the inner key of a declaration.", lower)
		out.printf("func %sEnvelopeKeys(variant %s) (string, string) {", lower, spec.variant)
		out.line("\tswitch variant {")

		for _, item := range entry.variants {
			out.printf("\tcase %s:", semanticName(item.code))
			out.printf("\t\treturn %q, %q", item.root, item.inner)
		}

		out.line("\tdefault:")
		out.line("\t\treturn \"\", \"\"")
		out.line("\t}")
		out.line("}")
		out.line("")

		out.printf("// %sEnvelope wraps the fields of a declaration the way the API expects them.", lower)
		out.printf("func %sEnvelope(variant %s, fields map[string]any) map[string]any {", lower, spec.variant)
		out.printf("\troot, inner := %sEnvelopeKeys(variant)", lower)
		out.line("\treturn map[string]any{")
		out.line("\t\troot: map[string]any{")
		out.line("\t\t\tinner: []any{fields},")
		out.line("\t\t},")
		out.line("\t}")
		out.line("}")
		out.line("")

		out.printf("// %sFieldsNotCarried lists the fields that a declaration type does not carry.", lower)
		out.printf("var %sFieldsNotCarried = map[string][]string{", lower)

		for _, item := range entry.variants {
			var missing []string
			for _, name := range entry.optional {
				if !hasFamily(entry.owner[name], item.family) {
					missing = append(missing, name)
				}
			}

			if len(missing) == 0 {
				continue
			}

			out.printf("\t%q: {", item.code)
			for _, name := range missing {
				out.printf("\t\t%q,", name)
			}
			out.line("\t},")
		}

		out.line("}")
		out.line("")

		out.printf("// %s submits a %s declaration.", spec.method, strings.ToLower(kind))
		out.printf("func (c *Client) %s(ctx context.Context, variant %s, declaration %s) ([]Submission, error) {",
			spec.method, spec.variant, spec.decl)
		out.printf("\tfields, err := %sFieldsOf(variant, declaration)", lower)
		out.line("\tif err != nil {")
		out.line("\t\treturn nil, err")
		out.line("\t}")
		out.line("")
		out.printf("\treturn c.submit(ctx, DocumentCode(variant), %sEnvelope(variant, fields))", lower)
		out.line("}")
		out.line("")

		out.printf("// %sFieldsOf turns a %s declaration into the fields of the payload.", lower, strings.ToLower(kind))
		out.printf("func %sFieldsOf(variant %s, declaration %s) (map[string]any, error) {", lower, spec.variant, spec.decl)
		out.printf("\tpayload := %s(declaration)", payloadOf)

		for _, name := range g.allFields(entry) {
			info := g.variantInfo(entry.variants[0], name)
			fieldKind, public := g.fieldKind(name, entry.variants[0].xsd, info, false)

			if !strings.HasPrefix(fieldKind, "nested:") {
				continue
			}

			sub := nestedName(kind, name)
			out.printf("\tpayload.%s = %s(variant, declaration.%s)", public, lower+sub, public)
		}

		out.line("")
		out.line("\tfields, err := declarationFields(payload)")
		out.line("\tif err != nil {")
		out.line("\t\treturn nil, err")
		out.line("\t}")
		out.printf("\tdropFields(fields, %sFieldsNotCarried[string(variant)])", lower)
		out.line("")
		out.line("\treturn fields, nil")
		out.line("}")
		out.line("")
	}
}

// emitOptionalHelpers writes the helpers of the optional values.
func (g *generator) emitOptionalHelpers(out *code) {
	kinds := make([]string, 0, len(g.usedOptional))
	for kind := range g.usedOptional {
		kinds = append(kinds, kind)
	}
	sort.Strings(kinds)

	emitted := map[string]bool{}

	for _, kind := range kinds {
		if kind == "flag" {
			// A boolean carries the three states on its own.
			out.line("// optBoolPtr converts an optional boolean into the wire encoding.")
			out.line("func optBoolPtr(value *bool) *wire.Bool {")
			out.line("\tif value == nil {")
			out.line("\t\treturn nil")
			out.line("\t}")
			out.line("\tanswer := wire.FromBool(*value)")
			out.line("\treturn &answer")
			out.line("}")
			out.line("")
			out.line("// boolPtrOf reads an optional boolean of the wire encoding.")
			out.line("func boolPtrOf(value *wire.Bool) *bool {")
			out.line("\tif value == nil {")
			out.line("\t\treturn nil")
			out.line("\t}")
			out.line("\tanswer := *value == wire.True")
			out.line("\treturn &answer")
			out.line("}")
			out.line("")

			continue
		}

		body := optionalBodies[kind]
		helper := optionalHelpers[kind]

		if emitted[helper.forward] {
			continue
		}
		emitted[helper.forward] = true
		emitted[helper.backward] = true

		out.printf("// %s converts an optional value into the wire encoding.", helper.forward)
		out.printf("func %s(value %s) %s {", helper.forward, body.public, body.wire)
		out.line("\tif value == nil {")
		out.line("\t\treturn nil")
		out.line("\t}")
		out.line("\t" + body.toWire)
		out.line("}")
		out.line("")

		out.printf("// %s reads an optional value of the wire encoding.", helper.backward)
		out.printf("func %s(value %s) %s {", helper.backward, body.wire, body.public)
		out.line("\tif value == nil {")
		out.line("\t\treturn nil")
		out.line("\t}")
		out.line("\t" + body.fromWire)
		out.line("}")
		out.line("")
	}
}

// emitGoldenTest writes the test that compares every payload with the
// reference payload of the Ministry.
func (g *generator) emitGoldenTest() error {
	out := &code{}
	out.line(generatedHeader)
	out.line("")
	out.line("package ergani")
	out.line("")
	out.line("import (")
	out.line("\t\"encoding/json\"")
	out.line("\t\"os\"")
	out.line("\t\"path/filepath\"")
	out.line("\t\"strings\"")
	out.line("\t\"testing\"")
	out.line("")
	out.line("\t\"github.com/takispanag/ergani-go-sdk/internal/wire\"")
	out.line(")")
	out.line("")

	out.line("// declarationSample is a reference payload of the Ministry and the way to")
	out.line("// turn it back into the payload of the SDK.")
	out.line("type declarationSample struct {")
	out.line("\t// name is the code of the declaration type.")
	out.line("\tname string")
	out.line("")
	out.line("\t// file is the name of the reference payload.")
	out.line("\tfile string")
	out.line("")
	out.line("\t// roundTrip turns the fields of the reference payload into the fields of")
	out.line("\t// the payload of the SDK.")
	out.line("\troundTrip func(map[string]any) (map[string]any, error)")
	out.line("}")
	out.line("")

	out.line("// declarationSamples are the reference payloads of every declaration type the")
	out.line("// SDK models.")
	out.line("var declarationSamples = []declarationSample{")

	for _, entry := range g.groups {
		spec := entry.spec
		lower := lowerName(spec.kind)

		for _, item := range entry.variants {
			name := semanticName(item.code)

			out.line("\t{")
			out.printf("\t\tname: %q,", item.code)
			out.printf("\t\tfile: %q,", item.sample)
			out.line("\t\troundTrip: func(fields map[string]any) (map[string]any, error) {")
			out.line("\t\t\traw, err := json.Marshal(fields)")
			out.line("\t\t\tif err != nil {")
			out.line("\t\t\t\treturn nil, err")
			out.line("\t\t\t}")
			out.line("")
			out.printf("\t\t\tvar payload wire.%s", spec.wire)
			out.line("\t\t\tif err := json.Unmarshal(raw, &payload); err != nil {")
			out.line("\t\t\t\treturn nil, err")
			out.line("\t\t\t}")
			out.line("")
			out.printf("\t\t\treturn %sFieldsOf(%s, %sDeclarationOf(payload))", lower, name, lower)
			out.line("\t\t},")
			out.line("\t},")
		}
	}

	out.line("}")
	out.line("")

	out.line("// TestDeclarationsMatchTheOfficialSamples checks the payload of every")
	out.line("// declaration type against the reference payload of the Ministry.")
	out.line("func TestDeclarationsMatchTheOfficialSamples(t *testing.T) {")
	out.line("\tfor _, sample := range declarationSamples {")
	out.line("\t\tt.Run(sample.name, func(t *testing.T) {")
	out.line("\t\t\twant := readDeclarationSample(t, sample.file)")
	out.line("")
	out.line("\t\t\tgot, err := sample.roundTrip(want)")
	out.line("\t\t\tif err != nil {")
	out.line("\t\t\t\tt.Fatalf(\"the payload of %s could not be built: %v\", sample.name, err)")
	out.line("\t\t\t}")
	out.line("")
	out.line("\t\t\tif diff := compareFields(got, want); len(diff) > 0 {")
	out.line("\t\t\t\tt.Errorf(\"the payload of %s does not match the official sample:\\n  %s\",")
	out.line("\t\t\t\t\tsample.name, strings.Join(diff, \"\\n  \"))")
	out.line("\t\t\t}")
	out.line("\t\t})")
	out.line("\t}")
	out.line("}")
	out.line("")

	out.line("// readDeclarationSample reads a reference payload and returns the fields of")
	out.line("// the declaration.")
	out.line("func readDeclarationSample(t *testing.T, name string) map[string]any {")
	out.line("\tt.Helper()")
	out.line("")
	out.line("\tpath := filepath.Join(\"testdata\", \"declarations\", name)")
	out.line("\tdata, err := os.ReadFile(path)")
	out.line("\tif err != nil {")
	out.line("\t\tt.Fatalf(\"Failed to read %s: %v\", path, err)")
	out.line("\t}")
	out.line("")
	out.line("\tvar document map[string]any")
	out.line("\tif err := json.Unmarshal(data, &document); err != nil {")
	out.line("\t\tt.Fatalf(\"Failed to decode %s: %v\", path, err)")
	out.line("\t}")
	out.line("")
	out.line("\tfor _, value := range document {")
	out.line("\t\tobject, ok := value.(map[string]any)")
	out.line("\t\tif !ok {")
	out.line("\t\t\tt.Fatalf(\"The root of %s does not hold an object\", path)")
	out.line("\t\t}")
	out.line("\t\tfor _, inner := range object {")
	out.line("\t\t\tif list, ok := inner.([]any); ok {")
	out.line("\t\t\t\tif len(list) == 0 {")
	out.line("\t\t\t\t\tt.Fatalf(\"The declaration of %s is empty\", path)")
	out.line("\t\t\t\t}")
	out.line("\t\t\t\tinner = list[0]")
	out.line("\t\t\t}")
	out.line("\t\t\tfields, ok := inner.(map[string]any)")
	out.line("\t\t\tif !ok {")
	out.line("\t\t\t\tt.Fatalf(\"The declaration of %s is not an object\", path)")
	out.line("\t\t\t}")
	out.line("\t\t\treturn fields")
	out.line("\t\t}")
	out.line("\t}")
	out.line("")
	out.line("\tt.Fatalf(\"The declaration of %s is empty\", path)")
	out.line("")
	out.line("\treturn nil")
	out.line("}")
	out.line("")

	return out.write(filepath.Join(g.root, "declarations_golden_test.go"))
}

// allFields returns the fields of a family of declarations, the ones every
// type of it carries first.
func (g *generator) allFields(entry *group) []string {
	fields := make([]string, 0, len(entry.shared)+len(entry.optional))
	fields = append(fields, entry.shared...)
	fields = append(fields, entry.optional...)

	return fields
}
